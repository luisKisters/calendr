#!/usr/bin/env node
// Prints the locked v11 design tokens (R10 · Mine, Dark + Paper "Clear tint") as computed by the mockup itself, for the Swift tests.
//   node scripts/v5-tokens.js <path to design/mockup-v11> [--swift]
// It loads the mockup's tokens.js / designer.js / readability.js (the mockup folder is not in this repository) and reads the
// locked look exactly as the page builds it (READ.look with the R10 preset). Only colour values are printed: no calendar data.
'use strict';
const path = require('path');
const dir = path.resolve(process.argv[2] || '');
const R = require(path.join(dir, 'readability.js'));
const p = R.PRESETS.find(x => x.id === 'R10');
const L = R.look(p.code, p.k);
// The Google swatches plus the v4 demo calendars of the app.
const HUES = ['#D9443A', '#E5674F', '#F2884B', '#E9B949', '#3FA36B', '#5FB97E', '#5DADE2', '#5B8DEF', '#A9A6F5', '#9254DE', '#B9B9B9', '#8E9AAF', '#F2C94C', '#888888'];
const CHROME = ['bg', 'rail', 'surface', 'raised', 'hover', 'hoverRail', 'selected', 'fg1', 'fg2', 'fg3', 'fg4', 'hourc', 'accent', 'onAccent', 'live', 'onLive',
  'focus', 'ok', 'warn', 'danger', 'segRing', 'grid', 'gridV', 'hairStrong', 'hair', 'todayTint'];
const EV = ['fill', 'fillH', 'fillSel', 'bar', 'title', 'titleSel', 'meta', 'metaSel', 'fillPast', 'titlePast', 'metaPast', 'barPast', 'fillDec', 'titleDec', 'edge'];
const out = { code: p.code, k: p.k, dark: {}, paper: {}, events: { dark: {}, paper: {} } };
for (const th of ['dark', 'paper']) {
  const t = L.T[th];
  for (const k of CHROME) out[th][k] = t[k];
  for (const h of HUES) { const e = L.ev(h, th); out.events[th][h] = Object.fromEntries(EV.map(k => [k, e[k]])); }
}
if (!process.argv.includes('--swift')) { console.log(JSON.stringify(out, null, 1)); process.exit(0); }
// Swift literal for Tests/HorionTests/PaletteV5Tests.swift
const q = s => `"${s}"`;
const lines = ['    // generated by: node scripts/v5-tokens.js design/mockup-v11 --swift   (look R, preset R10, k=' + p.k + ')'];
for (const th of ['dark', 'paper']) {
  lines.push(`    static let ${th}Chrome: [String: String] = [`);
  lines.push(CHROME.map(k => `        ${q(k)}: ${q(out[th][k])}`).join(',\n') + ',');
  lines.push('    ]');
  lines.push(`    static let ${th}Events: [String: [String: String]] = [`);
  for (const h of HUES) lines.push(`        ${q(h)}: [` + EV.map(k => `${q(k)}: ${q(out.events[th][h][k])}`).join(', ') + '],');
  lines.push('    ]');
}
console.log(lines.join('\n'));
